#!/usr/bin/env python3
"""Glyph_Envelope — the same hyperglyph at the data's minimum, median and maximum.

A hyperglyph is dialled in on one record, looks superb, and then the real
data goes in and parts fly apart, sink through the floor, or swallow each
other. It happens because the design quietly assumed a range the data does
not respect. The discipline that fixes it is small:

    declare a budget per variable    variable -> channel -> domain -> RANGE
    clamp into that range on the way in, not after something breaks
    build the glyph at the data's MIN, MEDIAN and MAX
    measure those three, look at one, and only then generate all N

Three glyphs tell you what a thousand would, in a fraction of the time.
This scene *is* those three glyphs, side by side, with the measurements
committed beside them in `extent_report.txt`.

The glyph is a palm tree, one per student, from Dr Dave Warner's Medical
Infoscope: a cube planter box you can grab and drag (pass/fail colour), four
stacked trunk segments -- one per family of tests, each thinner than the one
below and coloured by that family's mean score -- with a fan of branches off
each segment whose lift angle and bead size carry the individual test scores,
and a crown sphere for the CBSE score, sized and coloured by it. The design is
his; the numbers here are not.

    THE DATA IS SYNTHETIC. No real student records are used or bundled.
    `data/synthetic_cohort.csv` is generated by `make_cohort()` below from a
    seeded RNG, and exists only to give the envelope a domain to be measured
    against.

Every design decision that could break is a row in ENVELOPE, and `audit()`
enforces the two things the envelope exists to protect: nothing drops below
the baseline the box stands on, and no two parts of a glyph swallow each
other. Both are checked on all three probes before the scene is written.

    python build_glyph_envelope.py
"""
from __future__ import annotations

import sys
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent / "code"))

from gv_kernel import load_node_csv, Scene, node_world_matrix  # noqa: E402
from gv_extents import analyse, report, local_box  # noqa: E402

# ---------------------------------------------------------------------------
GEO_CUBE, GEO_SPHERE, GEO_CYLINDER, GEO_CIRCLE = 1, 3, 19, 24
TOPO_NONE = 0
TYPE_WORLD, TYPE_GLYPH = 0, 5
ROT_EULER = 0
BG = (16, 18, 24, 255)

# Test families, bottom of the trunk to the top, exactly as the design was
# dialled in: the widest family sits lowest.
GROUPS = [
    ("LAB/iRAT", ["LAB1", "LAB2", "IRAT1", "IRAT2"], (206, 92, 190)),
    ("Quizzes",  ["QUIZ1", "QUIZ2"],                 (222, 168, 66)),
    ("Core MCQ", ["MCQ1", "MCQ2", "MCQ3", "MCQ4", "MCQ5"], (104, 190, 118)),
    ("NBME",     ["NBME1", "NBME2"],                 (94, 152, 226)),
]
TESTS = [c for _, cols, _ in GROUPS for c in cols]

# ---------------------------------------------------------------------------
# THE DESIGN ENVELOPE
#
# variable -> channel -> domain (what the data does) -> range (the room the
# design gives it). Every range is CLAMPED at both ends, so no value, however
# extreme, can push a part outside the space allotted to it. Authored scales
# also stay at or above 0.2 so the scene reads the same whether or not the
# viewer has View > Enforce Minimum Glyph Size switched on (SKILL.md rule 6).
# ---------------------------------------------------------------------------
ENVELOPE = [
    # variable            channel                      domain        range
    ("group mean score",  "trunk segment colour",      "0..100",     "40..95 ROYGBV"),
    ("group mean score",  "branch lift angle",         "0..100",     "-24..+52 deg"),
    ("individual test",   "branch bead radius",        "0..100",     "0.21..0.46"),
    ("individual test",   "branch bead brightness",    "0..100",     "0.45..1.0"),
    ("CBSE score",        "crown radius",              "0..100",     "0.42..0.92"),
    ("CBSE score",        "crown colour",              "0..100",     "30..90 ROYGBV"),
    ("Step 1 pass/fail",  "planter box colour",        "{0, 1}",     "blue | red"),
]

LIFT_LO, LIFT_HI = -24.0, 52.0          # degrees, clamped
BEAD_LO, BEAD_HI = 0.21, 0.46           # authored sphere scale, clamped
CROWN_LO, CROWN_HI = 0.42, 0.92         # authored sphere scale, clamped
COLOUR_LO, COLOUR_HI = 40.0, 95.0       # segment ROYGBV endpoints
CROWN_COLOUR_LO, CROWN_COLOUR_HI = 30.0, 90.0

# Fixed proportions -- these do not carry data, so they are constants, not
# channels. Everything is in the root box's own units, and the box is scale 1,
# so they are world units too.
BOX_SCALE = 1.0
BOX_HALF = float(local_box(GEO_CUBE)[0][0])      # 0.5774 -- a cube is inscribed
SEG_H = 1.30                                     # trunk segment height
SEG_R0, SEG_TAPER = 0.36, 0.90                   # radius of the lowest segment, per level
BEADS = 5                                        # beads per branch
BEAD_STEP = 0.62                                 # along the branch
GLYPH_PITCH = 9.5                                # between the three probes

# Three numbers the envelope *chose*, not the designer. Each is the smallest
# value that keeps the audit below clean at the extremes, and each was found by
# running the audit rather than by looking at a picture:
#
#   BRANCH_R0   the innermost bead has to clear the trunk (0.30 + a full-size
#               bead 0.46) AND its neighbours around the fan; five branches at
#               0.85 put a 1.00 chord between them, which a 0.46 bead clears.
#   TRUNK_BASE  a bare lower trunk exists purely so the deepest droop still
#               clears the ground: 3.33 of reach at -24 degrees falls 1.35, and
#               the lowest hub has to be higher than that plus a bead radius.
#               The palm gained a stem because the data has a worst case.
#   BEAD_STEP   beads on one branch are meant to touch -- that is the necklace
#               pattern -- so the audit's rule is "no part's centre inside
#               another's silhouette", not "no overlap".
BRANCH_R0 = 0.85                                 # first bead's distance from the axis
TRUNK_BASE = 0.80                                # bare stem between rim and first segment

BASELINE_Z = 0.0                                 # the plane the planter sits on


# ---------------------------------------------------------------------------
# 1. SYNTHETIC COHORT
# ---------------------------------------------------------------------------
def make_cohort(n=189, seed=7) -> pd.DataFrame:
    """A believable spread of scores. Synthetic, seeded, and not anyone's data.

    One latent ability per student plus per-test noise, which is enough to give
    every variable a realistic domain -- a long left tail, a ceiling near 100,
    and a handful of records that sit at the extremes the envelope must survive.
    """
    rng = np.random.default_rng(seed)
    ability = rng.normal(68.0, 13.0, n)
    out = {"student": [f"S{i + 1:03d}" for i in range(n)]}
    for col in TESTS:
        out[col] = np.clip(ability + rng.normal(0.0, 9.0, n), 0.0, 100.0).round(1)
    out["CBSE"] = np.clip(ability * 0.85 + rng.normal(6.0, 5.0, n),
                          0.0, 100.0).round(1)
    df = pd.DataFrame(out)
    df["Step1_pass"] = (df.CBSE >= 45.0).astype(int)
    return df


def probes(df: pd.DataFrame) -> list[tuple[str, dict]]:
    """The three records to build: every variable at its min, median and max.

    Deliberately *not* three real students. A real minimum student is only
    minimal on some variables; the design has to survive the corner of the
    domain, which is the record that takes the extreme on every axis at once.
    """
    out = []
    for name, pick in (("minimum", lambda s: s.min()),
                       ("median", lambda s: s.median()),
                       ("maximum", lambda s: s.max())):
        rec = {c: float(pick(df[c])) for c in TESTS + ["CBSE"]}
        rec["Step1_pass"] = 0 if name == "minimum" else 1
        out.append((name, rec))
    return out


# ---------------------------------------------------------------------------
# 2. ENCODING -- every one of these clamps
# ---------------------------------------------------------------------------
def lerp(a, b, t):
    return a + (b - a) * min(1.0, max(0.0, t))


def roygbv(score, lo, hi) -> tuple[int, int, int]:
    """Red at `lo`, violet at `hi`, through orange/yellow/green/blue."""
    stops = [(214, 66, 58), (226, 132, 52), (222, 206, 74),
             (98, 186, 104), (76, 140, 226), (150, 96, 214)]
    t = min(1.0, max(0.0, (score - lo) / (hi - lo))) * (len(stops) - 1)
    i = min(int(t), len(stops) - 2)
    f = t - i
    return tuple(int(round(lerp(stops[i][k], stops[i + 1][k], f)))
                 for k in range(3))


def dim(rgb, k) -> tuple[int, int, int]:
    return tuple(int(round(c * k)) for c in rgb)


def lift_deg(score):
    return lerp(LIFT_LO, LIFT_HI, score / 100.0)


def bead_scale(score):
    return lerp(BEAD_LO, BEAD_HI, score / 100.0)


def crown_scale(score):
    return lerp(CROWN_LO, CROWN_HI, score / 100.0)


# ---------------------------------------------------------------------------
# 3. SCENE
# ---------------------------------------------------------------------------
COLUMNS = ["id", "type", "parent_id", "branch_level",
           "translate_x", "translate_y", "translate_z",
           "rotate_x", "rotate_y", "rotate_z",
           "scale_x", "scale_y", "scale_z",
           "color_r", "color_g", "color_b", "color_a",
           "geometry", "hide", "topo", "ratio", "show_text", "rotation_mode",
           "text"]

DEFAULTS = dict(translate_x=0.0, translate_y=0.0, translate_z=0.0,
                rotate_x=0.0, rotate_y=0.0, rotate_z=0.0,
                scale_x=1.0, scale_y=1.0, scale_z=1.0,
                color_r=255, color_g=255, color_b=255, color_a=255,
                geometry=GEO_SPHERE, hide=0, topo=TOPO_NONE, ratio=0.1,
                show_text=0, rotation_mode=ROT_EULER, text="")


@dataclass
class SceneBuilder:
    rows: list[dict] = field(default_factory=list)
    next_id: int = 1

    def add(self, **kw) -> int:
        self.rows.append({**DEFAULTS, "id": self.next_id, **kw})
        self.next_id += 1
        return self.next_id - 1

    def to_dataframe(self) -> pd.DataFrame:
        return pd.DataFrame(self.rows, columns=COLUMNS)


def sanitize(s: str) -> str:
    return "".join(c for c in s if c.isprintable() and c not in '",')


def build_palm(sb: SceneBuilder, rec: dict, x: float, label: str) -> int:
    """One palm. Returns the root box's id.

    Structure, and why it is shaped this way:

        box      root, a UNIFORM cube -- the drag handle, and the one node to
                 scale if the whole glyph needs resizing (SKILL.md rule 4)
        hub_i    hidden, uniform, scale 1, one per trunk segment. Everything
                 that has to keep its shape hangs off a hub rather than off the
                 segment, because a segment is deliberately long and thin and a
                 child of a non-uniform parent is stretched -- and sheared, if
                 it is also rotated (rule 13, the uniform carrier)
        seg_i    the visible trunk segment, a LEAF. It carries appearance only
        bead     branch beads, plain Cartesian offsets in the hub's frame:
                 no rotations anywhere in the glyph, so nothing can shear
        crown    the CBSE sphere, on the box so it rides the same uniform frame
    """
    box_rgb = (74, 132, 214) if rec["Step1_pass"] else (206, 74, 66)
    box = sb.add(type=TYPE_GLYPH, parent_id=0, branch_level=0,
                 translate_x=x, translate_y=0.0, translate_z=BOX_HALF * BOX_SCALE,
                 scale_x=BOX_SCALE, scale_y=BOX_SCALE, scale_z=BOX_SCALE,
                 geometry=GEO_CUBE, topo=TOPO_NONE,
                 color_r=box_rgb[0], color_g=box_rgb[1], color_b=box_rgb[2],
                 text=sanitize(f"{label} -- Step 1 "
                               f"{'pass' if rec['Step1_pass'] else 'fail'}"))

    rim = BOX_HALF                       # box-local z of the planter's rim
    stem_rgb = (128, 104, 84)
    sb.add(type=TYPE_GLYPH, parent_id=box, branch_level=1,
           translate_z=rim + TRUNK_BASE / 2.0,
           scale_x=SEG_R0 * 1.05, scale_y=SEG_R0 * 1.05,
           scale_z=TRUNK_BASE / 2.0,
           geometry=GEO_CYLINDER, topo=TOPO_NONE,
           color_r=stem_rgb[0], color_g=stem_rgb[1], color_b=stem_rgb[2],
           text=sanitize("bare stem -- carries no data; it is the clearance "
                         "the deepest branch droop needs"))

    top = rim + TRUNK_BASE               # first branch-bearing segment starts here
    for i, (gname, cols, group_hue) in enumerate(GROUPS):
        mean = float(np.mean([rec[c] for c in cols]))
        r = SEG_R0 * SEG_TAPER ** i
        z_lo = top + i * SEG_H
        z_mid = z_lo + SEG_H / 2.0

        hub = sb.add(type=TYPE_GLYPH, parent_id=box, branch_level=1,
                     translate_z=z_mid, hide=1, topo=TOPO_NONE,
                     text=sanitize(f"{gname} carrier (hidden, uniform)"))

        seg_rgb = roygbv(mean, COLOUR_LO, COLOUR_HI)
        sb.add(type=TYPE_GLYPH, parent_id=hub, branch_level=2,
               scale_x=r, scale_y=r, scale_z=SEG_H / 2.0,
               geometry=GEO_CYLINDER, topo=TOPO_NONE,
               color_r=seg_rgb[0], color_g=seg_rgb[1], color_b=seg_rgb[2],
               text=sanitize(f"{gname} mean {mean:.1f}"))

        # Segments carry the group MEAN on one ROYGBV ramp, so the trunk reads
        # as a single ranked column. The branches carry the individual scores
        # on their group's own HUE at varying brightness, so the four families
        # stay separable however well the student did -- a second variable
        # cannot ride the same channel as the first and still be read.
        lift = np.radians(lift_deg(mean))
        for b, col in enumerate(cols):
            az = np.radians(360.0 * b / len(cols) + 25.0 * i)
            score = rec[col]
            rad = bead_scale(score)
            bright = lerp(0.45, 1.0, score / 100.0)
            for k in range(BEADS):
                along = BRANCH_R0 + k * BEAD_STEP
                sb.add(type=TYPE_GLYPH, parent_id=hub, branch_level=2,
                       translate_x=float(np.cos(az) * along * np.cos(lift)),
                       translate_y=float(np.sin(az) * along * np.cos(lift)),
                       translate_z=float(along * np.sin(lift)),
                       scale_x=rad, scale_y=rad, scale_z=rad,
                       geometry=GEO_SPHERE, topo=TOPO_NONE,
                       **dict(zip(("color_r", "color_g", "color_b"),
                                  dim(group_hue, bright))),
                       text=sanitize(f"{col}: {score:.1f}"))

    cr = crown_scale(rec["CBSE"])
    crown_rgb = roygbv(rec["CBSE"], CROWN_COLOUR_LO, CROWN_COLOUR_HI)
    sb.add(type=TYPE_GLYPH, parent_id=box, branch_level=1,
           translate_z=top + len(GROUPS) * SEG_H + cr,
           scale_x=cr, scale_y=cr, scale_z=cr,
           geometry=GEO_SPHERE, topo=TOPO_NONE,
           color_r=crown_rgb[0], color_g=crown_rgb[1], color_b=crown_rgb[2],
           text=sanitize(f"CBSE: {rec['CBSE']:.1f}"))
    return box


def build_scene(df: pd.DataFrame) -> pd.DataFrame:
    sb = SceneBuilder()
    sb.add(type=TYPE_WORLD, parent_id=0, branch_level=0, geometry=0,
           color_r=BG[0], color_g=BG[1], color_b=BG[2], color_a=BG[3],
           text="World row: background colour only")

    for i, (name, rec) in enumerate(probes(df)):
        x = (i - 1) * GLYPH_PITCH
        build_palm(sb, rec, x, name)
        sb.add(type=TYPE_GLYPH, parent_id=0, branch_level=0,
               translate_x=x, translate_y=-4.6, translate_z=0.02,
               scale_x=0.6, scale_y=0.6, scale_z=0.6, ratio=0.02,
               geometry=GEO_CIRCLE, color_r=228, color_g=232, color_b=240,
               color_a=200, show_text=1,
               text=sanitize(f"{name} of every variable"))
    return sb.to_dataframe()


# ---------------------------------------------------------------------------
# 4. AUDIT -- the two things the envelope exists to protect
# ---------------------------------------------------------------------------
def drawn(path: Path, base_scale=1.0):
    """(id, label, centre, cols, half, geometry) for every node the app draws."""
    nodes = load_node_csv(str(path))
    scene = Scene(nodes, base_scale)
    out = []
    for n in nodes:
        if n.type != TYPE_GLYPH or n.hide or n.geometry == GEO_CIRCLE:
            continue
        m = node_world_matrix(n, scene)
        half, lcentre = local_box(n.geometry, n.ratio)
        centre = m[:3, 3] + m[:3, :3] @ lcentre
        out.append((n.id, n.text, centre, m[:3, :3], half, n.geometry))
    return out


def audit(path: Path, base_scale=1.0) -> list[str]:
    """Nothing below the baseline; no part's centre inside another part.

    Silhouettes come from `gv_extents._support`, the same per-geometry support
    function the checker uses -- a bounding sphere would call a trunk segment
    0.65 wide because it is 1.30 tall, and report the whole fan of branches as
    buried inside it.
    """
    from gv_extents import _support

    items = drawn(path, base_scale)
    errs = []

    for nid, text, c, cols, half, geo in items:
        bottom = c[2] - _support(cols, half, np.array([0.0, 0.0, 1.0]), geo)
        if bottom < BASELINE_Z - 1e-6:
            errs.append(f"id {nid} ({text}) reaches z = {bottom:+.3f}, "
                        f"below the baseline")

    for i in range(len(items)):
        ai, at, ac, acols, ahalf, ageo = items[i]
        for j in range(i + 1, len(items)):
            bi, bt, bc, bcols, bhalf, bgeo = items[j]
            v = bc - ac
            d = float(np.linalg.norm(v))
            if d < 1e-9:
                errs.append(f"id {ai} and id {bi} are coincident")
                continue
            u = v / d
            if d < _support(acols, ahalf, u, ageo) - 1e-6:
                errs.append(f"id {bi} ({bt}) has its centre inside "
                            f"id {ai} ({at}), {d:.3f} from it")
            elif d < _support(bcols, bhalf, -u, bgeo) - 1e-6:
                errs.append(f"id {ai} ({at}) has its centre inside "
                            f"id {bi} ({bt}), {d:.3f} from it")
    return errs


def main() -> int:
    df = make_cohort()
    data = HERE / "data" / "synthetic_cohort.csv"
    data.parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(data, index=False, encoding="utf-8", lineterminator="\r\n")

    print("variable domains in the synthetic cohort")
    for c in ["CBSE"] + TESTS[:3]:
        print(f"  {c:8} {df[c].min():6.1f} .. {df[c].median():6.1f} "
              f".. {df[c].max():6.1f}")

    scene = build_scene(df)
    out = HERE / "glyph_envelope_gv_node.csv"
    scene.to_csv(out, index=False, encoding="utf-8", lineterminator="\r\n",
                 float_format="%.4f")
    print(f"\n{out.name}: {len(scene)} rows, 3 probe glyphs")

    problems = audit(out)
    if problems:
        print(f"\n  !! the envelope does not hold ({len(problems)} faults)")
        for p in problems[:8]:
            print("     " + p)
        out.unlink()
        return 1
    print("  envelope holds at all three probes: nothing below the baseline, "
          "no part swallowed")

    txt = HERE / "extent_report.txt"
    lines = [
        "glyph_envelope_gv_node.csv -- committed alongside the scene so the",
        "measurements can be read without running anything.",
        "",
        "Regenerate with:  python ../../code/gv_extents.py "
        "glyph_envelope_gv_node.csv",
        "",
        "THE ENVELOPE",
        f"  {'variable':18} {'channel':26} {'domain':10} range",
    ]
    for v, ch, dom, rng in ENVELOPE:
        lines.append(f"  {v:18} {ch:26} {dom:10} {rng}")
    lines += ["", report(analyse(str(out), 1.0)), "",
              "AT GLOBAL SCALE 3", report(analyse(str(out), 3.0))]
    txt.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"  {txt.name} written")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
