#!/usr/bin/env python3
"""
Mesh Building Example — one tower, modelled and textured from scratch.

WHAT THIS DEMONSTRATES
----------------------
**Texture coordinates on an imported mesh.** Until 2026-09-17 GlyphViz threw a
mesh's UVs away on import, so a GEO_MESH node could only ever be one flat
colour and `texture_id` did nothing to it. It now keeps them, which is what
makes this scene possible: the tower's facade is a single 512x512 PNG,
generated by texkit.py, mapped so that **one texture tile is one storey
by three window bays** all the way up. Nothing about the window grid is
modelled — every window in the picture is a texel.

That is the whole argument for textures on meshes. The alternative, modelling
1,100 windows as geometry, would cost tens of thousands of triangles to say
something a 46 KB image says better.

**The mapping is the interesting part.** `meshkit.prism(uv_world=True)` runs
UVs past 1.0 in proportion to real size rather than normalizing 0..1 across
each face, so:

  * the same facade image serves the 44-storey tower and the 4-storey podium
    at the same apparent window size — no per-building texture, no rescaling;
  * a setback that makes one face narrower gets fewer bays across it, not
    squashed windows.

Both need the texture to tile seamlessly, which texkit's noise does by
construction (it is generated on a torus, not blurred at the edges).

WHAT IS IN THE SCENE
--------------------
One tower, built as five meshes because a GlyphViz node paints a mesh in one
colour: curtain wall, podium, the concrete core/crown, the glazed entrance
canopy, and the rooftop plant. Beside it sit the same meshes with their
textures removed, so the flat-colour and textured cases stand side by side.

Run:
    <glyphviz-env>\\python.exe mesh_creation_lab/Building/build_building.py
"""
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))   # the lab's toolkit

import meshkit as mk        # noqa: E402
import texkit as tk         # noqa: E402
from gvscene import SceneBuilder   # noqa: E402

STEM = "mesh_building"

# One "texture tile" is one storey tall. Everything below is in metres, and
# UV_PER_M turns metres into texture repeats, so a storey is 1.0 in v.
STOREY = 3.8
UV_PER_M = 1.0 / STOREY


# --------------------------------------------------------------------------
# the tower
# --------------------------------------------------------------------------

def build_tower() -> mk.Model:
    """A setback tower: a wide podium, a shaft that steps in twice, a
    concrete core that runs past the top, and rooftop plant."""
    m = mk.Model("tower")
    glass, podium, core, canopy, plant = (
        m.part('glass'), m.part('podium'), m.part('core'),
        m.part('canopy'), m.part('plant'))

    # ---- podium: 4 storeys, wider than the shaft ----
    pw, pd, ph = 46.0, 34.0, 4 * STOREY
    podium.extend(mk.prism(mk.rect(pw, pd), 0.0, ph,
                           uv_world=True, uv_scale=UV_PER_M))

    # ---- shaft: three stacked blocks, each stepping in ----
    # (width, depth, storeys) — the setbacks are what stop a tower reading as
    # an extruded rectangle, and they cost nothing but three prisms.
    blocks = [(34.0, 26.0, 22), (28.0, 21.0, 14), (21.0, 16.0, 8)]
    z = ph
    for w, d, storeys in blocks:
        h = storeys * STOREY
        glass.extend(mk.prism(mk.rect(w, d), z, z + h,
                              uv_world=True, uv_scale=UV_PER_M))
        # a spandrel band at each setback, in concrete rather than glass
        core.extend(mk.prism(mk.rect(w + 1.4, d + 1.4), z - 0.9, z + 0.9,
                             uv_world=True, uv_scale=UV_PER_M))
        z += h
    top = z

    # ---- the core: a blade running the full height and past the crown ----
    core.extend(mk.prism(mk.rect(7.0, 17.0), 0.0, top + 3 * STOREY,
                         uv_world=True, uv_scale=UV_PER_M))
    # crown parapet
    core.extend(mk.prism(mk.rect(21.0, 16.0), top, top + 0.9,
                         uv_world=True, uv_scale=UV_PER_M))

    # ---- entrance canopy: a thin glazed slab on brackets ----
    canopy.extend(mk.box(size=(20.0, 9.0, 0.5),
                         center=(0.0, -pd / 2 - 3.0, 5.4),
                         uv_world=True, uv_scale=0.08))
    for x in (-8.0, 0.0, 8.0):
        canopy.extend(mk.box(size=(0.45, 0.45, 5.4),
                             center=(x, -pd / 2 - 6.6, 2.7),
                             uv_world=True, uv_scale=0.25))

    # ---- rooftop plant: the clutter that makes a roof look used ----
    rng = np.random.default_rng(3)
    for _ in range(9):
        w = float(rng.uniform(1.6, 4.2))
        d = float(rng.uniform(1.6, 3.4))
        h = float(rng.uniform(1.2, 3.6))
        x = float(rng.uniform(-7.0, 7.0))
        y = float(rng.uniform(-5.5, 5.5))
        plant.extend(mk.box(size=(w, d, h), center=(x, y, top + h / 2 + 0.9),
                            uv_world=True, uv_scale=0.3))
    # a mast
    plant.extend(mk.revolve([(0.55, 0), (0.42, 6), (0.16, 14), (0.0, 19)],
                            segments=8).transform(
                                mk.translate(6.0, 4.0, top + 0.9)))
    return m


def main() -> int:
    mesh_dir, media_dir = HERE / "meshes", HERE / "media"
    for d in (mesh_dir, media_dir):
        d.mkdir(parents=True, exist_ok=True)
    for old in list(mesh_dir.glob("*.obj")) + list(media_dir.glob("*.png")):
        old.unlink()

    print("modelling...")
    tower = build_tower()
    tower.save(mesh_dir, prefix="tower_")
    for k, part in tower.parts.items():
        print(f"  {k:8s} {len(part):5d} tris")
    lo, hi = tower.bounds()
    height = float(hi[2] - lo[2])
    print(f"  overall {height:.1f} m tall")

    print("painting textures...")
    # 3 bays x 1 storey per tile: `cols`/`rows` set how many windows are in
    # the image, UV_PER_M sets how much building one image covers.
    tk.save(tk.facade(512, 512, cols=3, rows=1, seed=12, lit_fraction=0.42,
                      wall=(0.34, 0.36, 0.40)),
            media_dir / "facade_glass.png")
    tk.save(tk.facade(512, 512, cols=4, rows=1, seed=31, lit_fraction=0.55,
                      wall=(0.30, 0.28, 0.26), lit=(1.0, 0.92, 0.72)),
            media_dir / "facade_podium.png")
    conc = tk.fbm(256, 256, period=6, octaves=5, seed=9)
    tk.save(tk.tint(conc, (0.46, 0.45, 0.43), (0.66, 0.65, 0.62)),
            media_dir / "concrete.png")
    tk.save(tk.metal_panel(256, 256, seed=4, bands=4), media_dir / "metal.png")
    plaza = tk.fbm(256, 256, period=14, octaves=5, seed=21)
    tk.save(tk.tint(plaza, (0.38, 0.38, 0.40), (0.56, 0.56, 0.57)),
            media_dir / "plaza.png")

    print("building scene...")
    sb = SceneBuilder(HERE, STEM, background=(16, 20, 30),
                      tag_rgb=(225, 232, 245), fog=(320.0, 900.0))
    files = {k: f"tower_{k}.obj" for k in tower.parts}
    for f in files.values():
        sb.register_mesh(f)
    for t in ("concrete.png", "facade_glass.png", "facade_podium.png",
              "metal.png", "plaza.png"):
        sb.register_texture(t)

    # Which texture and tint each part wears. A textured node's colour
    # MULTIPLIES its texture, so these are near-white tints — see the tree
    # example, where getting this wrong rendered a whole grove black.
    SKIN = {
        'glass':  ("facade_glass.png",  (215, 228, 242)),
        'podium': ("facade_podium.png", (232, 226, 214)),
        'core':   ("concrete.png",      (226, 224, 219)),
        'canopy': ("metal.png",         (205, 222, 236)),
        'plant':  ("metal.png",         (198, 200, 204)),
    }
    asm = tower.assembly(anchor=(0.0, 0.0, 0.0))   # rig sits at the base

    def place(x, y, yaw, *, textured=True, label="", pin=False, scale=1.0):
        rig = sb.rig(pos=(x, y, 0.0), rot=(0, 0, yaw), scale=scale,
                     text=label, pin_text=pin)
        for key, part in asm.items():
            tex, tint = SKIN[key]
            sb.add(parent=rig.id, pos=part.offset, scale=part.scale,
                   mesh=files[key],
                   texture=tex if textured else 0,
                   # Untextured, the tint would render the tower white, so the
                   # flat-colour twin takes real materials instead.
                   color=tint if textured else FLAT[key])
        return rig

    FLAT = {'glass': (74, 96, 122), 'podium': (96, 88, 78),
            'core': (128, 126, 120), 'canopy': (110, 130, 150),
            'plant': (96, 98, 102)}

    # ---- plaza ----
    sb.add(pos=(0, 0, -0.6), scale=(190, 130, 0.6), color=(205, 208, 212),
           geometry=1, texture="plaza.png",
           text="Plaza — a built-in Cube glyph")

    # ---- the tower ----
    place(0, 0, 0, textured=True, pin=True,
          label="Textured — every window is a texel, not a triangle")

    # ---- the same meshes, untextured, for comparison ----
    place(-96, 6, 12, textured=False, pin=True,
          label="Same five meshes, textures off — one flat colour each")

    sb.finish()
    print()
    print(f"Open {HERE.name}/{STEM}_gv_node.csv in GlyphViz "
          "(meshes/ and media/ load automatically).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
